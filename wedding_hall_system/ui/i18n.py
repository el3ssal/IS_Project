def t(lang: str, key: str) -> str:
    """Translate ``key``; falls back to English, then to the key itself
    (a missing translation is visible, never silent)."""
    lang = lang if lang in STRINGS else "en"
    return STRINGS[lang].get(key) or STRINGS["en"].get(key) or key


def lang_for_token(db, auth, token) -> str:
    """Session language for a UI handler: the logged-in employee's
    preference, Arabic when there is no valid session (the venue
    default). Never raises — a bad token means 'ar', not a crash."""
    try:
        emp = auth.validate_session(token)
    except Exception:
        return "ar"
    if emp is None:
        return "ar"
    try:
        from ..logic.preferences import get_language

        return get_language(db, emp)
    except Exception:
        return "ar"


class LabelRegistry:
    """Collects the components a language toggle must rename/re-render.

    Factory methods create a component in Arabic (the venue default)
    and register it in one call, so a view builder never writes the
    same key twice:

    - ``labels``: (component, key) — the toggle returns
      ``gr.update(label=t(lang, key))``.
    - ``texts``: (component, key) — the toggle returns
      ``gr.update(value=t(lang, key))`` (Markdown headings, buttons).
    - ``tabs``: (tab, key) — the toggle returns
      ``gr.update(label=t(lang, key))`` for the tab button itself
      (verified against the Gradio 6.32 frontend: the TabItem reads
      its label reactively, so a label update re-renders the button).
    - ``choices``: {component: [(i18n_key, value), ...]} — fixed enum
      dropdowns whose visible options are translated too; the toggle
      returns ``gr.update(label=..., choices=[(t(lang, k), v), ...])``.
    - ``placeholders``: (component, key) — textboxes whose placeholder
      hint is translated; the toggle returns
      ``gr.update(placeholder=t(lang, key))``.

    ``result()`` returns the dict a builder returns to ``app.py``.
    """

    def __init__(self) -> None:
        self.labels: list = []
        self.texts: list = []
        self.tabs: list = []
        self.choices: dict = {}
        self.choices_fns: dict = {}
        self.placeholders: list = []

    def _add(self, comp, key: str, bucket: str):
        getattr(self, bucket).append((comp, key))
        return comp

    def textbox(self, key: str, placeholder_key: str | None = None, **kw):
        import gradio as gr

        if placeholder_key:
            kw["placeholder"] = t("ar", placeholder_key)
            comp = self._add(gr.Textbox(label=t("ar", key), **kw), key, "labels")
            self.placeholders.append((comp, placeholder_key))
            return comp
        return self._add(gr.Textbox(label=t("ar", key), **kw), key, "labels")

    def number(self, key: str, **kw):
        import gradio as gr

        return self._add(gr.Number(label=t("ar", key), **kw), key, "labels")

    def button(self, key: str, **kw):
        import gradio as gr

        return self._add(gr.Button(t("ar", key), **kw), key, "texts")

    def dropdown(self, key: str, choices, **kw):
        import gradio as gr

        return self._add(
            gr.Dropdown(choices=choices, label=t("ar", key), **kw), key, "labels")

    def dropdown_t(self, key: str, choice_keys, **kw):
        """Dropdown whose visible options are translated: ``choice_keys``
        is a list of (i18n_key, value); the stored value never changes."""
        import gradio as gr

        comp = gr.Dropdown(
            choices=[(t("ar", k), v) for k, v in choice_keys],
            label=t("ar", key), **kw)
        self.labels.append((comp, key))
        self.choices[comp] = list(choice_keys)
        return comp

    def dropdown_data(self, key: str, choices_fn, **kw):
        """Dropdown whose options come from the database plus a fixed
        'any' entry: ``choices_fn(lang)`` rebuilds the whole option
        list in the requested language, so the toggle re-runs it."""
        import gradio as gr

        comp = gr.Dropdown(choices=choices_fn("ar"), label=t("ar", key), **kw)
        self.labels.append((comp, key))
        self.choices_fns[comp] = choices_fn
        return comp

    def checkbox(self, key: str, **kw):
        import gradio as gr

        return self._add(gr.Checkbox(label=t("ar", key), **kw), key, "labels")

    def file(self, key: str, **kw):
        import gradio as gr

        return self._add(gr.File(label=t("ar", key), **kw), key, "labels")

    def image(self, key: str, **kw):
        import gradio as gr

        return self._add(gr.Image(label=t("ar", key), **kw), key, "labels")

    def checkbox_group(self, key: str, choices, **kw):
        import gradio as gr

        return self._add(
            gr.CheckboxGroup(choices=choices, label=t("ar", key), **kw),
            key, "labels")

    def radio(self, key: str, choices, **kw):
        import gradio as gr

        return self._add(
            gr.Radio(choices=choices, label=t("ar", key), **kw), key, "labels")

    def radio_t(self, key: str, choice_keys, **kw):
        """Radio whose visible options are translated like
        ``dropdown_t`` (``choice_keys`` is a list of (i18n_key,
        value))."""
        import gradio as gr

        comp = gr.Radio(
            choices=[(t("ar", k), v) for k, v in choice_keys],
            label=t("ar", key), **kw)
        self.labels.append((comp, key))
        self.choices[comp] = list(choice_keys)
        return comp

    def markdown(self, key: str, **kw):
        import gradio as gr

        return self._add(gr.Markdown(t("ar", key), **kw), key, "texts")

    def tab(self, key: str):
        """Context manager: ``with reg.tab("tab.halls"): ...``"""
        import contextlib

        import gradio as gr

        @contextlib.contextmanager
        def _open():
            tab = gr.Tab(t("ar", key))
            self.tabs.append((tab, key))
            with tab:
                yield tab

        return _open()

    def result(self) -> dict:
        return {"labels": list(self.labels), "texts": list(self.texts),
                "tabs": list(self.tabs), "choices": dict(self.choices),
                "choices_fns": dict(self.choices_fns),
                "placeholders": list(self.placeholders), "renders": []}


_EASTERN_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def _format_delta_ar(delta_min: int) -> str:
    """Arabic duration for an advisory reason (NFR-005): Eastern
    Arabic numerals with Arabic time words — never 'h'/'min'.
    1 → 'ساعة واحدة', 2 → 'ساعتان', 3–10 → 'N ساعات', 11+ → 'N ساعة'."""
    hours, minutes = divmod(int(delta_min), 60)

    def _hours(n: int) -> str:
        if n == 1:
            return "ساعة واحدة"
        if n == 2:
            return "ساعتان"
        num = str(n).translate(_EASTERN_DIGITS)
        return f"{num} ساعات" if 3 <= n <= 10 else f"{num} ساعة"

    def _minutes(n: int) -> str:
        return f"{str(n).translate(_EASTERN_DIGITS)} دقيقة"

    if hours and minutes:
        return f"{_hours(hours)} و{_minutes(minutes)}"
    if hours:
        return _hours(hours)
    return _minutes(minutes)


def format_advisory_reason(lang: str, suggestion) -> str:
    """Render a SchedulingSuggestion's plain-language reason."""
    params = dict(suggestion.reason_params)
    if "delta_min" in params:
        # The service stores raw minutes; the duration words are
        # rendered in the reader's language (English '6 h' must never
        # leak into the Arabic UI).
        minutes = params.pop("delta_min")
        if lang == "ar":
            params["delta"] = _format_delta_ar(minutes)
        else:
            hours, mins = divmod(int(minutes), 60)
            if hours and mins:
                params["delta"] = f"{hours} h {mins} min"
            elif hours:
                params["delta"] = f"{hours} h"
            else:
                params["delta"] = f"{mins} min"
    if "direction" in params:
        params["direction"] = t(
            lang, "advisory.earlier" if params["direction"] == "earlier"
            else "advisory.later")
    return t(lang, suggestion.reason_key).format(**params)


def translate_price_label(lang: str, label: str) -> str:
    """Translate a frozen price-breakdown label for display (Phase 8).

    Price labels are canonical English internally — the booking code
    parses them (``_selections_from_frozen_items``) — so they are
    translated here, at render time, by pattern. Service/package
    names are data and stay as-is; only the structural words move.
    Unknown labels pass through unchanged (never blank)."""
    import re

    if lang != "ar":
        return label
    label = str(label or "")
    m = re.match(r"^Hall — (.+)$", label)
    if m:
        return f"القاعة — {m.group(1)}"
    m = re.match(r"^Package — (.+)$", label)
    if m:
        return f"الباقة — {m.group(1)}"
    m = re.match(r"^Rule — (.+) \(([+-]?\d+)(%| EGP)\)$", label)
    if m:
        return f"قاعدة — {m.group(1)} ({m.group(2)}{m.group(3)})"
    m = re.match(r"^Extra guests — (\d+) × (.+)$", label)
    if m:
        return f"ضيوف إضافيون — {m.group(1)} × {m.group(2)}"
    m = re.match(r"^Service — (.+) \(included in package\)$", label)
    if m:
        return f"خدمة — {m.group(1)} (مشمولة في الباقة)"
    m = re.match(r"^Service — (.+) \((.+)\)$", label)
    if m:
        name, detail = m.group(1), m.group(2)
        if detail == "per guest":
            detail = "لكل ضيف"
        elif detail.endswith(" min"):
            detail = detail[:-4] + " دقيقة"
        elif detail.startswith("level × "):
            detail = "مستوى × " + detail[len("level × "):]
        return f"خدمة — {name} ({detail})"
    m = re.match(r"^Discount — (.+)$", label)
    if m:
        return f"خصم — {m.group(1)}"
    return label


def format_notification(lang: str, row: dict) -> tuple[str, str]:
    """Render one inbox row in ``lang``. Rows created after Phase 8
    carry ``data_json`` with ``title_key``/``body_key`` + params and
    are translated at read time (each reader sees their own
    language); older rows fall back to the stored English text."""
    import json

    try:
        data = json.loads(row.get("data_json") or "{}")
    except (ValueError, TypeError):
        data = {}
    title_key = data.get("title_key") if isinstance(data, dict) else None
    body_key = data.get("body_key") if isinstance(data, dict) else None
    params = data.get("params", {}) if isinstance(data, dict) else {}
    if title_key and body_key:
        # Enum values stored in params are rendered in the reader's
        # language: a task ``status`` param is a raw enum ("pending" /
        # "in_progress" / "completed") translated via ops keys, and a
        # payment ``method`` param via the booking method keys.
        params = dict(params)
        if isinstance(params.get("status"), str):
            status_key = {
                "pending": "ops.task_status_pending",
                "in_progress": "ops.task_status_in_progress",
                "completed": "ops.task_status_completed",
            }.get(params["status"])
            if status_key:
                params["status"] = t(lang, status_key)
        if isinstance(params.get("method"), str):
            method_key = {
                "cash": "booking.method_cash",
                "bank_transfer": "booking.method_bank_transfer",
                "visa_card": "booking.method_visa_card",
                "instapay": "booking.method_instapay",
                "other": "booking.method_other",
            }.get(params["method"])
            if method_key:
                params["method"] = t(lang, method_key)
        try:
            return (t(lang, title_key).format(**params),
                    t(lang, body_key).format(**params))
        except (KeyError, IndexError):
            pass
    return (row.get("title") or "", row.get("body") or "")


def dir_for(lang: str) -> str:
    """Layout direction: Arabic is RTL, English is LTR (SRS §16.3)."""
    return "rtl" if lang == "ar" else "ltr"


def dir_wrap(lang: str, markdown: str) -> str:
    """Wrap dynamically rendered Markdown in a directional container so
    the reading direction of the content switches with the language."""
    return f'<div dir="{dir_for(lang)}">\n\n{markdown}\n\n</div>'
